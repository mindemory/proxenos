def stored(vault, stream):
    out = vault / "raw" / "website" / stream
    lines = [line for path in sorted(out.glob("*.jsonl")) for line in path.read_text().splitlines()]
    return {r["id"]: r for r in map(json.loads, lines)}


def test_pages_keep_their_title_and_visible_text(repo, tmp_path):
    website.ingest(tmp_path, repo)
    pages = stored(tmp_path, "pages")

    assert pages["index.html"] == {
        "id": "index.html",
        "ts": "2023-01-15T15:00:00Z",  # first committed, not last changed
        "kind": "page",
        "title": "Kai's Lab & Notes",
        "url": "/",
        "text": "About me\nI study memory and attention.\nSecond para\nline two\nPython\n"
        "Made by hand, again",
        "words": 16,
        "date_from": "git",
    }
    post = pages["_posts/2024-03-05-first-post.md"]
    assert (post["kind"], post["title"]) == ("post", "First: a post")
    assert post["text"] == (
        'Ignored heading\nSome text with a link and .\none item\ntwo items\nprint("code")'
    )
    assert sorted(pages) == [
        "_posts/2024-03-05-first-post.md",
        "blog/2024/02/03/trip.html",
        "index.html",
        "notes/published.html",
        "pages/about.md",
        "projects/index.html",
    ]


def test_dates_come_from_front_matter_the_page_the_path_then_git(repo, tmp_path):
    website.ingest(tmp_path, repo)
    pages = stored(tmp_path, "pages")

    dated = {rel: (r["ts"], r["date_from"]) for rel, r in pages.items()}
    assert dated["_posts/2024-03-05-first-post.md"] == ("2024-03-05T15:00:00Z", "front matter")
    assert dated["notes/published.html"] == ("2022-05-06T05:08:09Z", "page")
    # An unmarked <time> isn't the published date, so the path wins.
    assert dated["blog/2024/02/03/trip.html"] == ("2024-02-03T00:00:00Z", "path")
    assert dated["projects/index.html"] == ("2024-06-01T12:00:00Z", "git")
    assert dated["pages/about.md"] == ("2023-01-15T15:00:00Z", "git")  # followed the rename

    urls = {rel: r["url"] for rel, r in pages.items()}
    assert urls["_posts/2024-03-05-first-post.md"] == "/life/notes/2024/03/05/first-post.html"
    assert urls["pages/about.md"] == "/about/"
    assert urls["projects/index.html"] == "/projects/"
    assert urls["blog/2024/02/03/trip.html"] == "/blog/2024/02/03/trip.html"
    assert pages["blog/2024/02/03/trip.html"]["title"] == "Trip"  # from the <h1>


def test_cv_entries_become_records(repo, tmp_path):
    website.ingest(tmp_path, repo)
    cv = stored(tmp_path, "cv")

    assert cv["cv_data.js#talks/memory-talk"] == {
        "id": "cv_data.js#talks/memory-talk",
        "ts": "2023-05-01T00:00:00Z",
        "section": "talks",
        "title": "Memory talk",
        "when": "May 2023",
        "entry": {"title": "Memory talk", "date": "May 2023", "url": "https://example.org/talk"},
        "date_from": "entry",
    }
    assert cv["cv_data.js#talks/memory-talk-2"]["ts"] == "2024-09-01T00:00:00Z"
    assert cv["cv_data.js#awards/best-poster"]["ts"] == "2019-01-01T00:00:00Z"
    # "In press" names no date, and "Market" isn't March.
    prize = cv["cv_data.js#awards/market-prize"]
    assert (prize["ts"], prize["date_from"]) == ("2023-01-15T15:00:00Z", "git")
    job = cv["cv_data.js#jobs/example-university"]
    assert (job["ts"], job["when"]) == (
        "2018-08-01T00:00:00Z",
        "Aug - Dec 2018; Jan 2021 - Present",
    )
    skills = cv["cv_data.js#skills/programming"]
    assert skills["entry"] == {"category": "Programming", "items": ["Python", "R"]}
    assert len(cv) == 7  # name and contact aren't entries, and cv.js is code


def test_reingest_is_idempotent_and_counts_files_with_no_date(repo, tmp_path):
    first = website.ingest(tmp_path, repo)
    assert first["added"] == 6 + 7 and first["undated"] == 1  # draft.html, never committed

    again = website.run(tmp_path, argparse.Namespace(repo=repo))
    assert again == {"read": 13, "added": 0, "updated": 0, "months_written": 0, "undated": 1}


def test_cv_data_that_will_not_parse_is_skipped_with_a_note(tmp_path, capsys):
    repo = tmp_path / "site"
    repo.mkdir()
    git(repo, "init", "-q")
    write(repo, {"cv_data.js": "const CV_DATA = build(`template ${x}`);\n", "a.html": "<p>a</p>"})
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "only")

    stats = website.ingest(tmp_path / "vault", repo)
    assert stats["added"] == 1
    assert "skipped cv_data.js" in capsys.readouterr().err


def test_a_directory_that_is_not_a_repo_is_refused(tmp_path, monkeypatch):
    monkeypatch.setenv("GIT_CEILING_DIRECTORIES", str(tmp_path.parent))
    with pytest.raises(SystemExit, match="not a git repository"):
        website.ingest(tmp_path / "vault", tmp_path)
